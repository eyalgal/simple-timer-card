SERVICE_FIELDS = {
    "create_timer": ["duration", "name", "command", "actions", "language", "icon", "color", "metadata"],
    "pause_timer": ["timer_id"],
    "unpause_timer": ["timer_id"],
    "cancel_timer": ["timer_id"],
    "finish_timer": ["timer_id"],
    "remove_timer": ["timer_id"],
    "add_time": ["timer_id", "duration_add"],
    "subtract_time": ["timer_id", "duration_add"],
    "restart_timer": ["timer_id", "duration_restart"],
    "get_timers": ["status"],
}


def build(lang: dict) -> dict:
    form = {
        "data": {"capture_voice_commands": lang["capture"], "late_action_minutes": lang["late"]},
        "data_description": {"capture_voice_commands": lang["capture_desc"], "late_action_minutes": lang["late_desc"]},
    }
    services = {}
    for service, fields in SERVICE_FIELDS.items():
        name, description = lang["services"][service]
        services[service] = {
            "name": name,
            "description": description,
            "fields": {
                field.split("_add")[0].split("_restart")[0]: {
                    "name": lang["fields"][field][0],
                    "description": lang["fields"][field][1],
                }
                for field in fields
            },
        }
    return {
        "config": {
            "step": {"user": {"title": lang["title"], "description": lang["setup_desc"], **form}},
            "abort": {"single_instance_allowed": lang["single"]},
        },
        "options": {"step": {"init": {"title": lang["options_title"], **form}}},
        "entity": {"sensor": {"timers": {"name": lang["entity"]}}},
        "exceptions": {
            "timer_not_found": {"message": lang["not_found"]},
            "invalid_duration": {"message": lang["invalid_duration"]},
            "command_not_understood": {"message": lang["not_understood"]},
            "command_and_actions": {"message": lang["both"]},
        },
        "selector": {"status": {"options": lang["statuses"]}},
        "services": services,
    }


def main() -> None:
    keys = set(T["en"])
    for code, lang in T.items():
        assert set(lang) == keys, f"{code} keys differ"
        assert set(lang["fields"]) == set(T["en"]["fields"]), f"{code} fields differ"
        assert set(lang["services"]) == set(T["en"]["services"]), f"{code} services differ"
        text = json.dumps(build(lang), ensure_ascii=False, indent=2) + "\n"
        (ROOT / "translations" / f"{code}.json").write_text(text, encoding="utf-8")
        if code == "en":
            (ROOT / "strings.json").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
